/** Lookup event type label by network and item_code */
export function lookupEventType(network: string, code: string): string | undefined {
  const l1 = EVENT_TYPE_L1[network]?.[code];
  if (l1) return l1;
  if (network === 'police') {
    return (
      POLICE_31_WEIGUI[code] ??
      POLICE_32_ANQUAN[code] ??
      POLICE_33_BEHAVIOR[code] ??
      POLICE_34_DATA[code] ??
      POLICE_35_DEVICE[code]
    );
  }
  if (network === 'mobilePolice') {
    return (
      MOBILE_21_EXPLOIT[code] ??
      MOBILE_22_WEB[code] ??
      MOBILE_23_BOTNET[code] ??
      MOBILE_24_WEAKNESS[code]
    );
  }
  if (network === 'internet') {
    return (
      INTERNET_41_SECURITY[code] ??
      INTERNET_42_NORMAL[code] ??
      INTERNET_43_WEB[code] ??
      INTERNET_44_CONTROL[code]
    );
  }
  return undefined;
}

/** Lookup vulnerability type label by item_code */
export function lookupVulnType(code: string): string | undefined {
  return (
    VULN_TYPE_L1[code] ??
    VULN_WEBVULN_SUB[code] ??
    VULN_SYSVULN_SUB[code] ??
    VULN_PASSWORD_SUB[code] ??
    VULN_COMPLIANCE_SUB[code] ??
    VULN_OTHER_SUB[code]
  );
}
